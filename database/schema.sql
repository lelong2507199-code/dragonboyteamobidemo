CREATE DATABASE IF NOT EXISTS dragonboy CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE dragonboy;
CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status ENUM('active','locked') NOT NULL DEFAULT 'active'
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS characters (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, account_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(16) NOT NULL UNIQUE, class_id TINYINT UNSIGNED NOT NULL DEFAULT 0,
 level INT UNSIGNED NOT NULL DEFAULT 1, exp BIGINT UNSIGNED NOT NULL DEFAULT 0,
 power BIGINT UNSIGNED NOT NULL DEFAULT 10, hp BIGINT UNSIGNED NOT NULL DEFAULT 100,
 max_hp BIGINT UNSIGNED NOT NULL DEFAULT 100, mp BIGINT UNSIGNED NOT NULL DEFAULT 50,
 max_mp BIGINT UNSIGNED NOT NULL DEFAULT 50, coins BIGINT UNSIGNED NOT NULL DEFAULT 0,
 map_id INT NOT NULL DEFAULT 0, x INT NOT NULL DEFAULT 150, y INT NOT NULL DEFAULT 390,
 kills BIGINT UNSIGNED NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_character_account FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS inventory (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, character_id BIGINT UNSIGNED NOT NULL,
 item_id INT NOT NULL, quantity INT UNSIGNED NOT NULL DEFAULT 1,
 upgrade_level TINYINT UNSIGNED NOT NULL DEFAULT 0,
 CONSTRAINT fk_inventory_character FOREIGN KEY(character_id) REFERENCES characters(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token CHAR(64) PRIMARY KEY, account_id BIGINT UNSIGNED NOT NULL,
 expires_at TIMESTAMP NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_session_account FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE,
 INDEX idx_session_expiry(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS character_battle (
 character_id BIGINT UNSIGNED PRIMARY KEY, enemy_hp INT UNSIGNED NOT NULL DEFAULT 100,
 enemy_max_hp INT UNSIGNED NOT NULL DEFAULT 100,
 CONSTRAINT fk_battle_character FOREIGN KEY(character_id) REFERENCES characters(id) ON DELETE CASCADE
) ENGINE=InnoDB;
